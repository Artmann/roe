#[test]
fn the_element_field_of_an_inline_array_is_never_flagged() {
    // `[InlineArray(n)]` requires exactly one instance field, and it is the
    // element storage behind every indexer and span access. Nothing names it.
    // An unused constant or static field in the same struct is not storage
    // and stays flagged.
    assert_findings(
        findings("inline_array", false),
        vec![member("App.Slots.Spare"), member("App.Slots.Unused")],
    );
}

#[test]
fn a_const_in_a_field_initializer_call_next_to_a_primary_constructor_parameter_is_used() {
    // `(int)MathF.Ceiling(A * ticks)` in a field initializer, where `ticks` is
    // a primary-constructor parameter, must still count as a use of `A`.
    assert_findings(findings("field_initializer_const", false), vec![]);
}

#[test]
fn fields_of_layout_sensitive_structs_are_never_flagged() {
    // Removing a field from a struct whose layout matters changes its size or
    // the offsets after it, which corrupts what the GPU or native code reads.
    // Evidence: [StructLayout], [FieldOffset], sizeof, Unsafe.SizeOf<T>, a T*
    // pointer, or a field named as padding. A struct with none of that, or
    // with an unrelated attribute, still gets its unused fields reported, and
    // so do constants and static fields, which take no space in the layout.
    assert_findings(
        findings("layout_structs", false),
        vec![
            member("App.GpuDecal.Spare"),
            member("App.GpuDecal.Unused"),
            member("App.Plain._unused"),
            member("App.Tagged._unused"),
        ],
    );
}

